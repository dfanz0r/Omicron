    /// <summary>
    ///     Returns the terminal display width of a Unicode code point.
    /// </summary>
    public static int GetWidth(int codePoint)
    {
        return GetWidth(new Rune(codePoint));
    }

    /// <summary>
    ///     Returns the terminal display width of a single rune.
    /// </summary>
    public static int GetWidth(Rune rune)
    {
        int code = rune.Value;

        // ASCII printable
        if (code >= 0x20 && code <= 0x7E)
        {
            return 1;
        }

        // Tab
        if (code == 0x09)
        {
            return 1;
        }

        // Control / C0 / C1 / Delete / soft hyphen
        if (code < 0x20 || code == 0x7F || (code >= 0x80 && code <= 0x9F))
        {
            return 0;
        }

        // Zero-width characters
        if (code == 0x00AD) // Soft hyphen
        {
            return 1; // Usually rendered as hyphen
        }

        if (
            code == 0x200B
            || code == 0x200C
            || code == 0x200D
            || // ZWSP, ZWNJ, ZWJ
            code == 0x2060
            || code == 0xFEFF
            || // Word joiner, BOM/ZWNBSP
            (code >= 0x200E && code <= 0x200F)
            || // LRM / RLM
            (code >= 0x2028 && code <= 0x202E)
            || // Line/paragraph separator, bidi controls
            (code >= 0x2061 && code <= 0x2064)
            || // Function application, invisible times, etc.
            (code >= 0x2066 && code <= 0x206F)
            || // Bidi controls
            code == 0x180B
            || code == 0x180C
            || code == 0x180D
            || // Mongolian variation selectors
            code == 0x180F
            || (code >= 0xFE00 && code <= 0xFE0F)
            || // Variation selectors
            (code >= 0xE0100 && code <= 0xE01EF)
            || // Variation selectors supplement
            (code >= 0xE0020 && code <= 0xE007F)
        ) // Tags
        {
            return 0;
        }

        // Combining marks
        if (IsInRanges(code, CombiningRanges))
        {
            return 0;
        }

        // CJK / Wide ranges
        if (IsInRanges(code, WideRanges))
        {
            return 2;
        }

        // Hangul Jamo is wide
        if (IsInRanges(code, HangulJamoRanges))
        {
            return 2;
        }

        // Emoji
        if (IsInRanges(code, EmojiRanges))
        {
            return 2;
        }

        // Regional indicator symbols (flag pairs)
        if (code >= 0x1F1E6 && code <= 0x1F1FF)
        {
            return 2;
        }

        // Enclosed alphanumerics
        if (code >= 0x2460 && code <= 0x24FF)
        {
            return 2;
        }

        // Box Drawing
        if (code >= 0x2500 && code <= 0x257F)
        {
            return 1; // Actually narrow in most terminals
        }

        // Block Elements
        if (code >= 0x2580 && code <= 0x259F)
        {
            return 1;
        }

        // Geometric Shapes
        if (code >= 0x25A0 && code <= 0x25FF)
        {
            return 1;
        }

        // Miscellaneous Symbols
        if (code >= 0x2600 && code <= 0x26FF)
        {
            return 1; // Most are narrow, but some are wide
        }

        // CJK Symbols and Punctuation (some narrow)
        if (code >= 0x3000 && code <= 0x303E)
        {
            return 2;
        }

        // Default for most other printable characters: width 1
        return 1;
    }

    /// <summary>
    ///     Returns the terminal column width of a UTF-8 byte sequence (typically a grapheme cluster).
    ///     Decodes the first rune to determine width.
    /// </summary>
    public static int GetWidth(ReadOnlySpan<byte> utf8)
    {
        if (utf8.IsEmpty)
        {
            return 0;
        }

        OperationStatus status = Rune.DecodeFromUtf8(utf8, out Rune rune, out _);
        if (status != OperationStatus.Done)
        {
            return 1; // Fallback for invalid UTF-8
        }

        return GetWidth(rune);
    }

    private static bool IsInRanges(int code, (int Start, int End)[] ranges)
    {
        // Binary search since ranges are sorted
        int lo = 0;
        int hi = ranges.Length - 1;

        while (lo <= hi)
        {
            int mid = lo + (hi - lo) / 2;
            (int Start, int End) r = ranges[mid];

            if (code < r.Start)
            {
                hi = mid - 1;
            }
            else if (code > r.End)
            {
                lo = mid + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }
